from __future__ import annotations

import argparse
import getpass
import hashlib
import os
import re
import secrets
import uuid
from pathlib import Path

from .database import Database


SERVER_ID_PATTERN = re.compile(r"[A-Za-z0-9_.-]{1,64}")
MATRIX_ID_PATTERN = re.compile(r"@[^\s:]+:\S+")


def token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def read_token_from_console() -> str:
    token = getpass.getpass("粘贴插件生成的 64 位 token（输入不回显）: ").strip()
    if not re.fullmatch(r"[0-9a-fA-F]{64}", token):
        raise SystemExit("token 必须是 64 个十六进制字符（256 位）")
    return token.casefold()


def main() -> None:
    parser = argparse.ArgumentParser(description="Matrix bridge server registry")
    subparsers = parser.add_subparsers(dest="command", required=True)

    add = subparsers.add_parser("add-server", help="add or rotate a server")
    add.add_argument("--id", required=True)
    add.add_argument("--name", required=True)
    add.add_argument("--group", default="main")
    add.add_argument("--port", type=int)
    add.add_argument(
        "--prompt-token",
        action="store_true",
        help="prompt invisibly for a token generated by the plugin",
    )

    set_token = subparsers.add_parser(
        "set-token", help="rotate an existing server token using hidden input"
    )
    set_token.add_argument("--id", required=True)

    subparsers.add_parser("list-servers", help="list registered servers")
    toggle = subparsers.add_parser("set-enabled", help="enable or disable a server")
    toggle.add_argument("--id", required=True)
    toggle.add_argument("--enabled", choices=("true", "false"), required=True)

    add_admin = subparsers.add_parser(
        "add-admin", help="add or update an explicitly authorized Matrix admin"
    )
    add_admin.add_argument("--matrix-id", required=True)
    add_admin.add_argument("--role", choices=("owner", "admin"), required=True)
    remove_admin = subparsers.add_parser(
        "remove-admin", help="remove an explicitly authorized Matrix admin"
    )
    remove_admin.add_argument("--matrix-id", required=True)
    subparsers.add_parser("list-admins", help="list authorized Matrix admins")

    args = parser.parse_args()
    database = Database(Path(os.getenv("DATABASE_PATH", "/data/bridge.db")))
    try:
        if args.command == "add-server":
            if not SERVER_ID_PATTERN.fullmatch(args.id):
                raise SystemExit("server-id 只能包含字母、数字、点、下划线或连字符，最长 64 字符")
            if not args.name.strip() or not args.group.strip():
                raise SystemExit("display-name 和 relay-group 不能为空")
            if args.port is not None and not 1 <= args.port <= 65535:
                raise SystemExit("port 必须在 1 到 65535 之间")
            token = read_token_from_console() if args.prompt_token else secrets.token_hex(32)
            database.save_server(
                args.id,
                args.name.strip(),
                token_hash(token),
                args.group.strip(),
                enabled=True,
            )
            if args.port is not None:
                database.update_server_hello(args.id, args.name.strip(), args.port)
            print(f"server-id: {args.id}")
            print(f"display-name: {args.name}")
            print(f"relay-group: {args.group}")
            print(f"game-port: {args.port or '-'}")
            if args.prompt_token:
                print("token: 已通过隐藏输入登记，不会再次显示。")
            else:
                print(f"token: {token}")
                print("请立即保存 token；数据库只保留 SHA-256 哈希，之后无法找回。")
        elif args.command == "set-token":
            token = read_token_from_console()
            if not database.rotate_server_token(args.id, token_hash(token)):
                raise SystemExit(f"unknown server-id: {args.id}")
            print(f"{args.id} 的 token 已轮换；旧连接会被拒绝。")
        elif args.command == "list-servers":
            for server in database.all_servers():
                state = "enabled" if server.enabled else "disabled"
                print(
                    f"{server.server_id}\t{server.display_name}\t"
                    f"{server.relay_group}\t{server.game_port or '-'}\t"
                    f"{state}\t{server.last_seen or '-'}"
                )
        elif args.command == "set-enabled":
            if not database.set_server_enabled(
                args.id, args.enabled == "true"
            ):
                raise SystemExit(f"unknown server-id: {args.id}")
        elif args.command == "add-admin":
            if not MATRIX_ID_PATTERN.fullmatch(args.matrix_id):
                raise SystemExit("matrix-id 格式无效，应类似 @name:example.org")
            try:
                changed = database.set_matrix_admin(
                    args.matrix_id,
                    args.role,
                    "console",
                    f"console:{uuid.uuid4()}",
                )
            except ValueError as error:
                raise SystemExit(str(error)) from error
            state = "已登记/更新" if changed else "身份未变化"
            print(f"{state}: {args.matrix_id} ({args.role})")
        elif args.command == "remove-admin":
            try:
                removed = database.remove_matrix_admin(
                    args.matrix_id,
                    "console",
                    f"console:{uuid.uuid4()}",
                )
            except ValueError as error:
                raise SystemExit(str(error)) from error
            if not removed:
                raise SystemExit(f"unknown matrix admin: {args.matrix_id}")
            print(f"已移除管理员: {args.matrix_id}")
        elif args.command == "list-admins":
            for admin in database.all_matrix_admins():
                print(
                    f"{admin.matrix_id}\t{admin.role}\t"
                    f"added-by={admin.added_by}\tupdated={admin.updated_at}"
                )
    finally:
        database.close()


if __name__ == "__main__":
    main()
